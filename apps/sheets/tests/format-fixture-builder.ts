// ── Invalid XLS fixture (for failure path) ─────────────────────────────

/**
 * Create an invalid XLS file — garbage bytes with .xls extension.
 * Used to test that conversion failure produces a typed error + cleans
 * up the conversion temp directory (no leak).
 */
export function writeInvalidXlsFixture(path: string): void {
  // Not a valid OLE2 compound document (wrong magic bytes).
  writeFileSync(path, Buffer.from('This is not a valid XLS file\n'))
}
